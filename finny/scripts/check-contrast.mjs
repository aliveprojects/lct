// Проверка контраста пар «текст / фон» темы «Космос» (src/styles/app.css). Порог WCAG 2.1 AA для обычного текста — 4,5 : 1.
// Прозрачные слои (стекло) заранее «смешаны» с небом, поэтому в таблице — итоговые цвета.
// Запуск: node scripts/check-contrast.mjs
const parse = (c) => c.replace('#', '').match(/../g).map((h) => parseInt(h, 16));
const lin = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
const lum = (rgb) => 0.2126 * lin(rgb[0]) + 0.7152 * lin(rgb[1]) + 0.0722 * lin(rgb[2]);
const ratio = (a, b) => { const [x, y] = [lum(parse(a)), lum(parse(b))].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
/** Смешивает цвет fg с прозрачностью alpha поверх bg. */
const over = (fg, alpha, bg) => '#' + parse(fg).map((v, i) => Math.round(v * alpha + parse(bg)[i] * (1 - alpha)).toString(16).padStart(2, '0')).join('');

const SKY = '#141a5b';                                   // самое светлое место неба под карточками
const glass = over('#363c98', 0.9, SKY);                 // .surface-2
const card = over('#1e2470', 0.84, SKY);                 // .surface
const sheet = '#141a5e';
const tint = (c, a) => over(c, a, card);

const PAIRS = [
  ['Основной текст на небе', '#f4f6ff', '#0e1240'],
  ['Основной текст на карточке', '#f4f6ff', card],
  ['Основной текст на «стекле»', '#f4f6ff', glass],
  ['Вторичный текст на небе', '#bcc4f5', SKY],
  ['Вторичный текст на карточке', '#bcc4f5', card],
  ['Вторичный текст в окне', '#bcc4f5', sheet],
  ['Кнопка: тёмный на бирюзовом', '#06133a', '#63f3e0'],
  ['Кнопка: тёмный на голубом (конец градиента)', '#06133a', '#3ea6ff'],
  ['Кнопка «Отложить»: тёмный на зелёном', '#06133a', '#7bf6bd'],
  ['Кнопка «Завершить»: тёмный на золотом', '#2e1d00', '#ffab1f'],
  ['Вторичная кнопка / ссылка на карточке', '#8ff5e9', card],
  ['Ссылка «режим экспертов» на тёмной «таблетке»', '#8ff5e9', '#080b2e'],
  ['Тег «Нужное»', '#8dbdff', tint('#5a8cff', 0.22)],
  ['Тег «Хочется»', '#ffab8c', tint('#ff7d55', 0.2)],
  ['Тег «Копилка»', '#78f4b8', tint('#3cdc96', 0.18)],
  ['Предупреждение', '#ffd88f', tint('#ffbe3c', 0.17)],
  ['Золотая карточка', '#f4f6ff', tint('#ffc93c', 0.17)],
  ['Облачко питомца', '#0e1240', '#f4f6ff'],
  ['Всплывающее сообщение', '#0e1240', '#f4f6ff'],
  ['Имя питомца на планете', '#f4f6ff', '#5a49d8'],
  ['Настроение «всё хорошо»', '#78f4b8', '#12365a'],
  ['Настроение «просит заботы»', '#ffc0a8', '#4a2338'],
  ['Сегмент плана «нужное»: тёмный на голубом', '#06133a', '#8dbdff'],
  ['Сегмент плана «хочется»: тёмный на персиковом', '#06133a', '#ffab8c'],
  ['Заголовок «Финни» (градиент, самая тёмная часть)', '#7ff3e4', '#0e1240'],
  ['Высокий контраст: белый на чёрном', '#ffffff', '#000000'],
  ['Высокий контраст: чёрный на жёлтом', '#000000', '#ffe600'],
];
let bad = 0;
for (const [name, fg, bg] of PAIRS) {
  const r = ratio(fg, bg);
  const ok = r >= 4.5;
  if (!ok) bad++;
  console.log(`${ok ? 'OK ' : 'НИЗКО'}  ${r.toFixed(2).padStart(5)}  ${name}  (${fg} на ${bg})`);
}
console.log(bad ? `\nНиже порога 4,5: ${bad}` : `\nВсе ${PAIRS.length} пар не ниже 4,5 : 1`);
process.exit(bad ? 1 : 0);
